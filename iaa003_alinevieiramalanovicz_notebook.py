import statsmodels.api as sm
import numpy as np

# Vamos obter as contagens necessárias para o teste de duas proporções na nossa amostra
# Comparando Século 20 vs Século 21
try:
    # Sucessos (Séries / TV Show) em cada período
    s_seculo20 = tabela_amostra.loc['Século 20', 'TV Show']
    s_seculo21 = tabela_amostra.loc['Século 21', 'TV Show']

    # Total de observações em cada período na amostra
    n_seculo20 = tabela_amostra.loc['Século 20'].sum()
    n_seculo21 = tabela_amostra.loc['Século 21'].sum()

    print("=== DADOS DA AMOSTRA PARA O TESTE ===")
    print(f"Século 20: {s_seculo20} Séries de um total de {n_seculo20} títulos (Proporção: {s_seculo20/n_seculo20:.2%})")
    print(f"Século 21: {s_seculo21} Séries de um total de {n_seculo21} títulos (Proporção: {s_seculo21/n_seculo21:.2%})")

    # Teste Z para duas proporções independentes
    successes = np.array([s_seculo20, s_seculo21])
    nobs = np.array([n_seculo20, n_seculo21])

    z_stat, p_val = sm.stats.proportions_ztest(successes, nobs, alternative='two-sided')

    print("\n=== TESTE Z PARA DUAS PROPORÇÕES (Séries no Século 20 vs Século 21) ===")
    print(f"Estatística Z: {z_stat:.4f}")
    print(f"p-valor: {p_val:.4g}")

    alpha = 0.05
    if p_val < alpha:
        print("\nResultado: Rejeitamos a hipótese nula ($H_0$).")
        print("A proporção de séries em relação a filmes é significativamente diferente entre os séculos na amostra.")
    else:
        print("\nResultado: Não rejeitamos a hipótese nula ($H_0$).")
        print("Não há diferença estatisticamente significativa na proporção de séries entre os séculos na amostra.")
except Exception as e:
    print(f"Erro ao executar o teste: {e}. Verifique se a amostragem foi executada previamente.")