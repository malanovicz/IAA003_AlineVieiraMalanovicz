"""Hipóteses para testar se os anos médios de
lançamento dos filmes e séries são diferentes:

H0:μSéries=μFilmes

H1:μSéries≠μFilmes
"""

import statsmodels.stats.weightstats as st
df_anoANDfilmes = df[df['type'] ==   'Movie']['release_year']
df_anoANDseries = df[df['type'] == 'TV Show']['release_year']
dsw1 = st.DescrStatsW(df_anoANDfilmes)
dsw2 = st.DescrStatsW(df_anoANDseries)
cm = st.CompareMeans(dsw1, dsw2)
# Calcule o número de observações, a média e o desvio padrão para cada grupo.
n_filmes = dsw1.nobs
n_series = dsw2.nobs
mean_filmes = dsw1.mean
mean_series = dsw2.mean
sd_filmes = dsw1.std
sd_series = dsw2.std
print(f'n_filmes = {n_filmes}')
print(f'mean_filmes = {mean_filmes}')
print(f'sd_filmes = {sd_filmes}')
print()
print(f'n_series = {n_series}')
print(f'mean_series = {mean_series}')
print(f'sd_series = {sd_series}')
print()
# realizar teste de hipótese
ht = cm.ztest_ind(alternative = 'two-sided', usevar = 'unequal', value = 0)
# calcule e imprima o erro padrão, o escore Z e o valor-p para o teste de hipótese.
se = cm.std_meandiff_separatevar
testZ = ht[0]
p_value = ht[1]
print(f'Standard error = {se}')
print(f'Test statistic: Z = {testZ}')
print(f'p-value = {p_value}')
# rejeitar ou aceitar a hipótese nula
if(p_value) < 0.05:
    print('\n rejeitar a hipótese nula')
else:
    print('\n aceitar a hipótese nula')

